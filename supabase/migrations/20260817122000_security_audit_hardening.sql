BEGIN;

ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS role TEXT;
UPDATE public.profiles SET role = 'operacao' WHERE role IS NULL OR role NOT IN ('admin', 'gerente', 'operacao');
ALTER TABLE public.profiles ALTER COLUMN role SET DEFAULT 'operacao';
ALTER TABLE public.profiles ALTER COLUMN role SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'profiles_role_check') THEN
        ALTER TABLE public.profiles
        ADD CONSTRAINT profiles_role_check CHECK (role IN ('admin', 'gerente', 'operacao')) NOT VALID;
        ALTER TABLE public.profiles VALIDATE CONSTRAINT profiles_role_check;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT role FROM public.profiles WHERE id = auth.uid()
$$;
REVOKE ALL ON FUNCTION public.get_user_role() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_user_role() TO authenticated;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.profiles (id, email, nome, role)
    VALUES (
        NEW.id,
        NEW.email,
        NEW.raw_user_meta_data ->> 'nome',
        'operacao'
    )
    ON CONFLICT (id) DO UPDATE SET
        email = EXCLUDED.email,
        nome = COALESCE(EXCLUDED.nome, public.profiles.nome);

    INSERT INTO public.categorias_financeiras (user_id, codigo, nome, natureza, grupo_dre)
    VALUES
        (NEW.id, 'locacao', 'Receita de locação', 'receita', 'receita_operacional'),
        (NEW.id, 'receita_nao_classificada', 'Receita não classificada', 'receita', 'receita_operacional'),
        (NEW.id, 'venda_ativo', 'Venda de veículo', 'receita', 'resultado_nao_operacional'),
        (NEW.id, 'manutencao', 'Manutenção', 'despesa', 'custos_servicos'),
        (NEW.id, 'seguro', 'Seguro', 'despesa', 'custos_servicos'),
        (NEW.id, 'principal_financiamento', 'Principal de financiamento', 'despesa', 'fluxo_financiamento'),
        (NEW.id, 'juros_encargos', 'Juros e encargos', 'despesa', 'resultado_financeiro'),
        (NEW.id, 'tributos_receita', 'Tributos sobre receita', 'deducao', 'deducoes_receita'),
        (NEW.id, 'nao_classificada', 'Não classificada', 'despesa', 'despesas_operacionais')
    ON CONFLICT (user_id, codigo) DO NOTHING;

    INSERT INTO public.configuracoes (user_id)
    VALUES (NEW.id)
    ON CONFLICT (user_id) DO NOTHING;
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT OR UPDATE OF email, raw_user_meta_data ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

DROP POLICY IF EXISTS "Users can insert own profile" ON public.profiles;
