CREATE OR REPLACE FUNCTION public.prevent_unauthorized_role_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NEW.role IS DISTINCT FROM OLD.role
       AND NOT EXISTS (
           SELECT 1 FROM public.profiles
           WHERE id = auth.uid() AND role = 'admin'
       )
    THEN
        RAISE EXCEPTION 'Alteração de perfil não autorizada';
    END IF;
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.prevent_unauthorized_role_change() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS prevent_unauthorized_role_change ON public.profiles;
CREATE TRIGGER prevent_unauthorized_role_change
BEFORE UPDATE OF role ON public.profiles
FOR EACH ROW EXECUTE FUNCTION public.prevent_unauthorized_role_change();

CREATE OR REPLACE FUNCTION public.set_profile_role(target_user UUID, new_role TEXT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF public.get_user_role() <> 'admin' THEN RAISE EXCEPTION 'Acesso negado'; END IF;
    IF new_role NOT IN ('admin', 'gerente', 'operacao') THEN RAISE EXCEPTION 'Perfil inválido'; END IF;
    IF new_role <> 'admin'
       AND (SELECT role FROM public.profiles WHERE id = target_user) = 'admin'
       AND (SELECT COUNT(*) FROM public.profiles WHERE role = 'admin') <= 1
    THEN
        RAISE EXCEPTION 'O último administrador não pode ser rebaixado';
    END IF;
    UPDATE public.profiles SET role = new_role WHERE id = target_user;
    IF NOT FOUND THEN RAISE EXCEPTION 'Usuário não encontrado'; END IF;
END;
$$;
REVOKE ALL ON FUNCTION public.set_profile_role(UUID, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_profile_role(UUID, TEXT) TO authenticated;

