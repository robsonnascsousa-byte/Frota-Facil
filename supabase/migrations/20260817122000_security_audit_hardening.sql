CREATE OR REPLACE FUNCTION public.log_audit_event()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    row_data JSONB;
    record_key TEXT;
    actor_role TEXT;
    request_headers JSONB;
BEGIN
    row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
    record_key := COALESCE(row_data ->> 'id', 'sem-id');
    SELECT role INTO actor_role FROM public.profiles WHERE id = auth.uid();
    BEGIN
        request_headers := NULLIF(current_setting('request.headers', TRUE), '')::jsonb;
    EXCEPTION WHEN OTHERS THEN
        request_headers := NULL;
    END;

    INSERT INTO public.audit_logs (
        schema_name, table_name, record_id, operation, old_data, new_data,
        user_id, user_role, txid, request_id, changed_at
    ) VALUES (
        TG_TABLE_SCHEMA, TG_TABLE_NAME, record_key, TG_OP,
        CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) END,
        CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) END,
        auth.uid(), COALESCE(actor_role, 'operacao'), txid_current(),
        request_headers ->> 'x-request-id',
        NOW()
    );
    RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.log_audit_event() FROM PUBLIC, anon, authenticated;

DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'veiculos', 'motoristas', 'contratos', 'pagamentos', 'receitas',
        'despesas', 'manutencoes', 'multas', 'sinistros', 'categorias_financeiras', 'profiles'
    ]
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS audit_%I ON public.%I', table_name, table_name);
        EXECUTE format(
            'CREATE TRIGGER audit_%I AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.log_audit_event()',
            table_name, table_name
        );
    END LOOP;
END;
$$;

